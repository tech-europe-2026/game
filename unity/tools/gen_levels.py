"""Generates Assets/Scripts/Levels.cs from coordinate-based layouts (x right, y up)."""
import os


class Grid:
    def __init__(self, w, h):
        self.w, self.h = w, h
        self.g = [[' '] * w for _ in range(h)]

    def put(self, x, y, ch):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.g[y][x] = ch

    def rect(self, x0, y0, x1, y1, ch):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.put(x, y, ch)

    def row(self, x0, x1, y, ch):
        self.rect(x0, y, x1, y, ch)

    def rows(self):
        return [''.join(self.g[y]).rstrip() for y in range(self.h - 1, -1, -1)]


