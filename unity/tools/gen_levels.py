def cs_rows(g):
    return ',\n'.join('            "' + r + '"' for r in g.rows())


def main():
    levels = [
        ("ROLL & BOUNCE", "jump,crouch", "ARROWS/A-D roll   SPACE jump   S crouch through tunnels", level1()),
        ("SPIN & GROW", "dash,grow", "SHIFT spin-dash breaks cracked walls   G grow: heavy, smashes floors", level2b()),
        ("BLINK & FREEZE", "teleport,freeze,invis", "T blink through glass   F freeze to skate lava   V vanish past lasers", level3()),
    ]
    out = ["// Generated by tools/gen_levels.py", "public static class Levels", "{",
           "    public struct Level { public string name, unlock, hint; public string[] map; }", "",
           "    public static readonly Level[] All =", "    {"]
    for name, unlock, hint, g in levels:
        out.append("        new Level { name = \"%s\", unlock = \"%s\", hint = \"%s\", map = new[]\n        {\n%s\n        } }," % (name, unlock, hint, cs_rows(g)))
    out += ["    };", "}", ""]
    path = os.path.join(os.path.dirname(__file__), '..', 'Assets', 'Scripts', 'Levels.cs')
    open(path, 'w').write('\n'.join(out))
    for _, _, _, g in levels:
        print('\n'.join(g.rows()))
        print('-' * 40)


main()
